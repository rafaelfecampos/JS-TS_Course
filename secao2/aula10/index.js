//op aritiméticos
let a = 10;
let b = 2;
console.log(`a = ${a}`);
console.log(`b = ${b}`);
//soma
console.log(`a+b = ${a+b}`);

//subtraction
console.log(`a-b = ${a-b}`);

//multiplication
console.log(`a*b = ${a*b}`);

//division
console.log(`a/b = ${a/b}`);

//exp
console.log(`a^b = ${a**b}`);

//expression
console.log(`a*(a-b) = ${a*(a-b)}`);

//counter
console.log(`a count delayed 1 = ${a++}`);//the function is executed first
console.log(`a count delayed 2 = ${a++}`);
console.log(`a count delayed 3 = ${a++}`);
console.log(`a count 1 = ${++a}`);//the counter is executed first
console.log(`a count 2 = ${++a}`);
console.log(`a count 3 = ${++a}`);

console.log(`a count delayed -1 = ${a--}`);
console.log(`a count delayed -2 = ${a--}`);
console.log(`a count delayed -3 = ${a--}`);
console.log(`a count -1 = ${--a}`);
console.log(`a count -2 = ${--a}`);
console.log(`a count -3 = ${--a}`);
